import { chromium, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import { readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const reference=process.env.IFC_GIS_REFERENCE || path.resolve(root,'../bim-gis-reference');
const text=await readFile(path.join(root,'frontend/.env.local'),'utf8');
const token=process.env.MAPBOX_TEST_TOKEN || text.match(/^VITE_MAPBOX_ACCESS_TOKEN=(.+)$/m)?.[1]?.trim();
if(!token?.startsWith('pk.')) throw new Error('Missing public token');
const output=path.join(root,'reports/mapbox-reference');await mkdir(output,{recursive:true});
const server=spawn(path.join(root,'.venv/Scripts/python.exe'),['-m','http.server','4181','--bind','127.0.0.1','--directory',reference],{windowsHide:true,stdio:'ignore'});
let browser;
try {
  const deadline=Date.now()+10000;
  while(Date.now()<deadline) { try { if((await fetch('http://127.0.0.1:4181')).ok) break; } catch{} await new Promise(r=>setTimeout(r,200)); }
  browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1440,height:800}});
  const errors=[];page.on('pageerror',e=>{ errors.push(e.message);console.log('Reference error:',e.stack?.replace(/pk\.[A-Za-z0-9._-]+/g,'[token]')); });
  await page.addInitScript(token=>{localStorage.setItem('mapbox-public-token',token);if(!localStorage.getItem('coordinates')) localStorage.setItem('coordinates',JSON.stringify([106.701,10.775]));},token);
  await page.goto('http://127.0.0.1:4181/index.html');
  await page.locator('#sample-button').click();
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('modelsNames') || '[]').length>0,null,{timeout:60000});
  await page.goto('http://127.0.0.1:4181/gis.html');
  await expect(page.locator('.mapboxgl-canvas')).toHaveCount(1);
  await page.waitForTimeout(4000);
  await page.locator('.mapboxgl-ctrl-geocoder input').pressSequentially('Ho Chi Minh City',{delay:40});
  await page.locator('.suggestions li').first().waitFor({timeout:30000});
  await page.locator('.suggestions li').first().click();
  const geocoded=await page.evaluate(()=>JSON.parse(localStorage.getItem('coordinates')));
  expect(geocoded).not.toEqual([106.701,10.775]);
  await page.locator('#coord').click();await page.waitForLoadState();
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('coordinates')))).toEqual(geocoded);
  await expect(page.locator('.mapboxgl-canvas')).toHaveCount(1);
  await page.waitForTimeout(4000);await page.screenshot({path:path.join(output,'01-globe.png')});
  await page.locator('#fly').click();await page.waitForTimeout(14000);
  await page.screenshot({path:path.join(output,'02-ifc-on-map.png')});
  for(let n=0;n<4;n++) await page.locator('.mapboxgl-ctrl-zoom-out').click();
  await page.waitForTimeout(2500);await page.screenshot({path:path.join(output,'03-city.png')});
  const box=await page.locator('.mapboxgl-canvas').boundingBox();
  await page.mouse.move(box.width*.65,box.height*.55);await page.mouse.down({button:'right'});
  await page.mouse.move(box.width*.65+160,box.height*.55-45,{steps:10});await page.mouse.up({button:'right'});
  await page.waitForTimeout(1500);await page.screenshot({path:path.join(output,'04-city-orbit.png')});
  await page.locator('#markerVis').click();await expect(page.locator('.mapboxgl-marker')).toHaveCount(0);
  await page.locator('#markerVis').click();await expect(page.locator('.mapboxgl-marker')).toHaveCount(1);
  await page.locator('#fly').click();await page.waitForTimeout(13000);
  await page.locator('#random').click();await page.waitForLoadState();
  await expect(page.locator('.mapboxgl-canvas')).toHaveCount(1);
  expect(errors).toEqual([]);
  console.log('PASS restored upstream IFC conversion, geocoder, move to pin, globe/model flight, city orbit, marker toggle and random move; no page errors');
} finally { await browser?.close();server.kill(); }
